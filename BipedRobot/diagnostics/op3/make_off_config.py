"""Writes config/op3_budget_off.yaml from config/op3_budget_r17wS.yaml: the same file with budgets off, as c17plain is to r17j. Only the first comment line
and the token_budget block change (tests/test_op3_env.py checks that nothing else differs). Usage: python diagnostics/op3/make_off_config.py"""
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
HEAD = ("# OP3 BUDGETS OFF (12 Nov 2026): op3_budget_r17wS.yaml with budgets off, as c17plain against r17j: the same three costs measured and logged, rates far\n"
        "# above any cost so no bucket ever empties, every episode at u = 1 and no budget relabeling: plain SAC with hindsight command relabeling. Generated by\n"
        "# diagnostics/op3/make_off_config.py; only token_budget differs from op3_budget_r17wS.yaml. The r17wS header follows.\n")
OFF = """token_budget:
  costs: [flight, slip, jshake]  # the same three costs as op3_budget_r17wS.yaml, measured and logged, but no budget acts on them
  rate_min: [10.0, 10.0, 10.0]  # budgets off, as c17plain: rates far above any cost, so no bucket ever empties
  rate_max: [20.0, 20.0, 20.0]
  overdraft: soft  # inert here; kept so the two configs differ only in rates and relabel shares
  u_low: -0.3  # inert here (p_unconstrained 1.0 sets u = 1 every episode)
  settle_steps: 5  # kept, so the logged costs are defined as in the budgets-on arm
  burst_steps: 100
  window_steps: 100
  p_unconstrained: 1.0
  p_keep: 1.0
  p_achieved: 0.0
  alive_bonus: 0.2
  curriculum: true
"""


def main() -> None:
    on = (REPO / "config/op3_budget_r17wS.yaml").read_text()
    i = on.index("\ntoken_budget:\n") + 1
    (REPO / "config/op3_budget_off.yaml").write_text(HEAD + on[:i] + OFF)
    print("wrote config/op3_budget_off.yaml")


if __name__ == "__main__":
    main()
