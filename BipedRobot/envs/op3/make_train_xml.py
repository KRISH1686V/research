"""Writes envs/assets/robotis_op3/op3_train.xml and scene_train.xml from the unmodified MuJoCo Menagerie files beside them.

Changes to op3.xml, each applied exactly once (the script stops if a pattern is not found exactly once):
  1. The 8 arm and head joints are removed (welded): head_pan, head_tilt, l/r_sho_pitch, l/r_sho_roll, l/r_el. Each body keeps its mass and
     inertia and is fixed at the neutral pose below, written as the body's axisangle about the removed joint's own axis (the joints sit at their
     body's origin, so this is exactly the pose the joint would hold). Their 8 position actuators are removed.
  2. The 12 leg actuators are renamed after their joints (l_hip_yaw_act -> l_hip_yaw), because HERLocoEnv finds actuators and joints by one name.
     Gains, force range and control range stay as Menagerie has them: kp 21.1 N m/rad, force range +-5 N m.
  3. The four foot boxes get names (r_sole_long, r_sole_wide, l_sole_long, l_sole_wide) so the env can find them. Size, position, friction unchanged.
Everything else (masses, inertias, joint damping 1.084, armature 0.045, frictionloss 0.03, collision hulls, solref 0.004) is Menagerie's.

Neutral pose (rad): arms down at the sides, about 19 deg out from vertical, elbows straight, head level: l_sho_roll 1.25, r_sho_roll -1.25, all others 0.
No self-contact at this pose with the legs at the env's standing pose (checked by tests/test_op3_env.py).

Usage: python envs/op3/make_train_xml.py   (rewrites the two files; tests/test_op3_env.py checks they match what this script writes)
"""
from __future__ import annotations

import re
from pathlib import Path

ASSETS = Path(__file__).resolve().parents[1] / "assets" / "robotis_op3"
WELD = {"head_pan": 0.0, "head_tilt": 0.0, "l_sho_pitch": 0.0, "l_sho_roll": 1.25, "l_el": 0.0, "r_sho_pitch": 0.0, "r_sho_roll": -1.25, "r_el": 0.0}
LEGS = ("l_hip_yaw", "l_hip_roll", "l_hip_pitch", "l_knee", "l_ank_pitch", "l_ank_roll", "r_hip_yaw", "r_hip_roll", "r_hip_pitch", "r_knee", "r_ank_pitch", "r_ank_roll")
SOLES = {'pos="0.024 0.013 -0.0265" size="0.0635 0.028 0.004"': "l_sole_long", 'pos="0.024 0.0125 -0.0265" size="0.057 0.039 0.004"': "l_sole_wide",
         'pos="0.024 -0.013 -0.0265" size="0.0635 0.028 0.004"': "r_sole_long", 'pos="0.024 -0.0125 -0.0265" size="0.057 0.039 0.004"': "r_sole_wide"}


def _once(text: str, pattern: str, repl, flags=0) -> str:
    out, n = re.subn(pattern, repl, text, flags=flags)
    if n != 1:
        raise RuntimeError(f"pattern {pattern!r} matched {n} times, expected 1: the Menagerie file changed")
    return out


def build_robot(src: str) -> str:
    text = _once(src, r'<mujoco model="robotis_op3">', '<mujoco model="robotis_op3_train">\n  <!-- GENERATED by BipedRobot/envs/op3/make_train_xml.py from op3.xml (MuJoCo Menagerie). Do not edit. -->')
    for joint, angle in WELD.items():
        m = re.search(rf'\n\s*<joint name="{joint}" axis="([^"]+)"/>', text)
        if m is None or text.count(f'<joint name="{joint}" ') != 1:
            raise RuntimeError(f"joint {joint} not found exactly once")
        axis = m.group(1)
        text = text[:m.start()] + text[m.end():]
        if angle:
            text = _once(text, rf'(<body name="{joint}_link" pos="[^"]+")>', rf'\1 axisangle="{axis} {angle!r}">')
        text = _once(text, rf'\n\s*<position name="{joint}_act" joint="{joint}"/>', "")
    for joint in LEGS:
        text = _once(text, rf'<position name="{joint}_act" joint="{joint}"/>', f'<position name="{joint}" joint="{joint}"/>')
    for attrs, name in SOLES.items():
        text = _once(text, re.escape(f'<geom class="foot" {attrs}/>'), f'<geom name="{name}" class="foot" {attrs}/>')
    return text


def build_scene(src: str) -> str:
    text = _once(src, r'<include file="op3.xml"/>', '<include file="op3_train.xml"/>')
    return _once(text, r'<mujoco model="op3 scene">', '<mujoco model="op3 train scene">\n  <!-- GENERATED by BipedRobot/envs/op3/make_train_xml.py from scene.xml (MuJoCo Menagerie). Do not edit. -->')


def outputs() -> dict:
    return {ASSETS / "op3_train.xml": build_robot((ASSETS / "op3.xml").read_text()),
            ASSETS / "scene_train.xml": build_scene((ASSETS / "scene.xml").read_text())}


if __name__ == "__main__":
    for path, text in outputs().items():
        path.write_text(text)
        print(f"wrote {path}")
